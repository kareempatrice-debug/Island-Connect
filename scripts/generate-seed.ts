/*
 * Generates supabase/seed.sql (reference data) and supabase/demo.sql (demo
 * listings) from the TypeScript files in src/data, so there is one source of truth.
 * Run with: npm run seed:generate
 */
import { writeFileSync } from "node:fs";
import { countries, districts, islands } from "../src/data/geography";
import { categories, categoryIcons, disabledIn } from "../src/data/categories";
import { demoBusinesses } from "../src/data/demo";

const s = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const arr = (v: string[]) => `array[${v.map(s).join(", ")}]::text[]`;

const seed: string[] = [
  "-- Generated by scripts/generate-seed.ts. Do not edit by hand.",
  "-- Reference data: countries, islands, districts, categories.",
  "begin;",
];

for (const c of countries) {
  seed.push(
    `insert into public.countries (code, name, short_name, currency_code, time_zone, dialling_code, district_label, sort_order) values (${s(c.code)}, ${s(c.name)}, ${s(c.shortName)}, ${s(c.currency)}, ${s(c.timeZone)}, ${s(c.diallingCode)}, ${s(c.districtLabel)}, ${c.sortOrder}) on conflict (code) do update set name = excluded.name, short_name = excluded.short_name, currency_code = excluded.currency_code, time_zone = excluded.time_zone, dialling_code = excluded.dialling_code, district_label = excluded.district_label, sort_order = excluded.sort_order;`,
  );
}
for (const i of islands) {
  seed.push(
    `insert into public.islands (country_code, slug, name, lat, lng, is_main) values (${s(i.countryCode)}, ${s(i.slug)}, ${s(i.name)}, ${n(i.lat)}, ${n(i.lng)}, ${i.isMain}) on conflict (country_code, slug) do update set name = excluded.name, lat = excluded.lat, lng = excluded.lng, is_main = excluded.is_main;`,
  );
}
for (const d of districts) {
  const island = d.islandSlug
    ? `(select id from public.islands where country_code = ${s(d.countryCode)} and slug = ${s(d.islandSlug)})`
    : "null";
  seed.push(
    `insert into public.districts (country_code, island_id, slug, name) values (${s(d.countryCode)}, ${island}, ${s(d.slug)}, ${s(d.name)}) on conflict (country_code, slug) do update set name = excluded.name, island_id = excluded.island_id;`,
  );
}
for (const c of categories) {
  const parent = c.parentSlug ? `(select id from public.categories where slug = ${s(c.parentSlug)})` : "null";
  seed.push(
    `insert into public.categories (parent_id, slug, name, description, icon, booking_models, sort_order) values (${parent}, ${s(c.slug)}, ${s(c.name)}, ${s(c.description)}, ${s(categoryIcons[c.slug] ?? null)}, ${arr(c.bookingModels)}, ${c.sortOrder}) on conflict (slug) do update set parent_id = excluded.parent_id, name = excluded.name, description = excluded.description, icon = excluded.icon, booking_models = excluded.booking_models, sort_order = excluded.sort_order;`,
  );
}
for (const country of countries) {
  const off = disabledIn[country.code] ?? [];
  seed.push(
    `insert into public.country_categories (country_code, category_id, is_enabled) select ${s(country.code)}, id, not (slug = any(${arr(off)})) from public.categories on conflict (country_code, category_id) do nothing;`,
  );
}
seed.push("commit;");
writeFileSync("supabase/seed.sql", seed.join("\n") + "\n");

const demo: string[] = [
  "-- Generated by scripts/generate-seed.ts. Do not edit by hand.",
  "-- DEMONSTRATION LISTINGS. Invented businesses for showing the app. Remove with supabase/remove-demo.sql.",
  "begin;",
];
for (const b of demoBusinesses) {
  const id = `(select id from public.businesses where slug = ${s(b.slug)})`;
  demo.push(
    `insert into public.businesses (slug, name, tagline, description, payment_methods, cancellation_policy, verification_status, listing_status, is_demo, is_featured, created_at) values (${s(b.slug)}, ${s(b.name)}, ${s(b.tagline)}, ${s(b.description)}, ${arr(b.paymentMethods)}, ${s(b.cancellationPolicy)}, 'unverified', 'published', true, ${b.isFeatured ? "true" : "false"}, now() - interval '${b.daysAgo} days') on conflict (slug) do nothing;`,
  );
  const L = b.location;
  demo.push(
    `insert into public.business_locations (business_id, country_code, island_id, district_id, landmark, lat, lng, is_primary) select ${id}, ${s(L.country)}, (select id from public.islands where country_code = ${s(L.country)} and slug = ${s(L.island)}), (select id from public.districts where country_code = ${s(L.country)} and slug = ${s(L.district)}), ${s(L.landmark)}, ${n(L.lat)}, ${n(L.lng)}, true where not exists (select 1 from public.business_locations where business_id = ${id});`,
  );
  for (const area of b.serves) {
    demo.push(
      `insert into public.business_service_areas (business_id, island_id) select ${id}, id from public.islands where country_code = ${s(area.country)} and slug = ${s(area.island)} on conflict do nothing;`,
    );
  }
  b.categories.forEach((slug, i) =>
    demo.push(
      `insert into public.business_categories (business_id, category_id, is_primary) select ${id}, id, ${i === 0} from public.categories where slug = ${s(slug)} on conflict do nothing;`,
    ),
  );
  b.services.forEach((sv, i) =>
    demo.push(
      `insert into public.services (business_id, name, description, price_min, price_max, price_unit, duration_minutes, booking_models, sort_order) select ${id}, ${s(sv.name)}, ${s(sv.description ?? null)}, ${n(sv.min)}, ${n(sv.max)}, ${s(sv.unit ?? null)}, ${n(sv.minutes)}, ${arr(sv.models)}, ${i} where not exists (select 1 from public.services where business_id = ${id} and name = ${s(sv.name)});`,
    ),
  );
  if (b.hours.length) {
    const values = b.hours.map((h) => `(${h.weekday}, ${s(h.opens)}::time, ${s(h.closes)}::time)`).join(", ");
    demo.push(
      `insert into public.opening_hours (business_id, weekday, opens, closes) select ${id}, v.w, v.o, v.c from (values ${values}) as v(w, o, c) where not exists (select 1 from public.opening_hours where business_id = ${id});`,
    );
  }
}
demo.push("commit;");
writeFileSync("supabase/demo.sql", demo.join("\n") + "\n");
console.log(`Wrote supabase/seed.sql (${seed.length} lines) and supabase/demo.sql (${demo.length} lines)`);
